def translate(key, lang=DEFAULT_LANGUAGE, **kwargs):
    """
    Look up `key` for `lang`, falling back to English if the language or
    the specific key is missing (keeps half-finished translations from
    ever showing a blank/broken label), then formats it with kwargs.
    """
    table = _STRINGS.get(lang) or _STRINGS[DEFAULT_LANGUAGE]
    text = table.get(key) or _STRINGS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return text.format(**kwargs)
    except Exception:
        return text


